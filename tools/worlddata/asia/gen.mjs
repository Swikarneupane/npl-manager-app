// Builds src/data/world/nations/<CODE>.js from in/<CODE>.txt. Usage: node gen.mjs CODE...
import { readFileSync, writeFileSync } from 'node:fs';
const OUT = new URL('../../../src/data/world/nations/', import.meta.url).pathname.replace(/%20/g, ' ');
const IN = new URL('./in/', import.meta.url);
const slug = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
for (const code of process.argv.slice(2)) {
  const meta = { sources: [], teams: [], notes: [], comps: [] }; const players = []; const seen = new Set();
  for (let line of readFileSync(new URL(`${code}.txt`, IN), 'utf8').split('\n')) {
    line = line.trim(); if (!line || line.startsWith('//')) continue;
    if (line.startsWith('#')) { const [k, ...v] = line.slice(1).split(' '); const val = v.join(' ');
      if (k === 'source') meta.sources.push(val); else if (k === 'note') meta.notes.push(val);
      // #team ID|Name|SHORT|level  (level: 1 top division, 2 second, 3 plate; optional)
      else if (k === 'team') { const [id, name, short, level] = val.split('|'); meta.teams.push({ id, name, short, kind: 'domestic', ...(level ? { level: +level } : {}) }); }
      else if (k === 'comp') meta.comps.push(val);
      else meta[k] = val; continue; }
    const f = line.split(';').map((x) => x.trim()); if (f.length !== 9) throw new Error(`${code}: bad line ${line}`);
    const [name, born, role, bat, bowl, type, hand, fms, teams] = f;
    const fm = {}; let gen = false;
    if (fms && fms !== '-') { for (const part of fms.split(',')) { if (part === 'g') { gen = true; continue; } if (part === 'u') { fm.unv = 1; continue; } const [t20, odi, fc] = part.split('/').map(Number); if (t20) fm.t20 = t20; if (odi) fm.odi = odi; if (fc) fm.fc = fc; } }
    if (gen) fm.gen = 1;
    let id = `${code.toLowerCase()}-${slug(name)}`; let k = 2; while (seen.has(id)) id = `${code.toLowerCase()}-${slug(name)}-${k++}`; seen.add(id);
    const regs = [code, ...teams.split(/\s+/).filter((t) => t && t !== '-' && t !== code)];
    players.push([id, name, code, +born, role, +bat, +bowl, type === '-' ? '' : type, hand, fm, regs]);
  }
  const J = (x) => JSON.stringify(x).replace(/"/g, "'").replace(/'(\w+)':/g, '$1: ').replace(/,(?=\S)/g, ', ');
  const esc = (r) => JSON.stringify(r).replace(/"([a-z0-9]+)":/g, '$1: ').replace(/,/g, ', ');
  let s = `// ${meta.name}: national and domestic players. Ratings are the game's estimates.\n`;
  s += `// record: [id, name, nat, born, role, bat, bowl, type, hand, fm, teams]  (see docs/world/ARCHITECTURE.md)\n`;
  s += `// Real players carry only name, nationality, birth year, role, batting hand, bowling type and team registrations.\n`;
  for (const n of meta.notes) s += `// ${n}\n`;
  s += `// Generated by a one-off script from hand-checked source lists; edit the records directly from now on.\n`;
  s += `export default {\n  code: '${code}', name: ${JSON.stringify(meta.name)}, member: '${meta.member}', asOf: '${meta.asOf}',\n  sources: [\n${meta.sources.map((x) => `    ${JSON.stringify(x)},`).join('\n')}\n  ],\n  players: [\n`;
  s += players.map((r) => `    ${esc(r)},`).join('\n') + '\n  ],\n  teams: [\n';
  s += meta.teams.map((t) => `    ${esc(t)},`).join('\n') + (meta.teams.length ? '\n' : '') + `  ],\n  comps: ${JSON.stringify(meta.comps).replace(/,/g, ", ")},\n};\n`;
  writeFileSync(OUT + code + '.js', s); console.log(code, players.length);
}
